const M = 1_000_000;

/**
 * Builds a three-year financial summary from revenue, adjusted EBITDA and gross
 * margin inputs so the CIM table always ties to the teaser figures (FY2025).
 */
function financials(
  revenue: [number, number, number],
  adjEbitda: [number, number, number],
  grossMargin: [number, number, number],
  addBackPct: number,
  capexPct: number,
): CimFinancialYear[] {
  const years = ["FY2023", "FY2024", "FY2025"];
  const r = (n: number) => Math.round(n / 1000) * 1000;
  return years.map((year, i) => {
    const rev = r(revenue[i] * M);
    const adj = r(adjEbitda[i] * M);
    const addBacks = r(adj * addBackPct);
    const reported = adj - addBacks;
    const grossProfit = r(rev * grossMargin[i]);
    return {
      year,
      revenue: rev,
      grossProfit,
      operatingExpenses: grossProfit - reported,
      reportedEbitda: reported,
      addBacks,
      adjustedEbitda: adj,
      capex: r(rev * capexPct),
    };
  });
}

